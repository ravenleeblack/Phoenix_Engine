static float clamp_text_channel(float value)
{
    // object_frag switches to texture sampling above 0.99 on all channels,
    // so keep text just under that threshold.
    return (value > 0.985f) ? 0.985f : value;
}

void draw_text_element(VkCommandBuffer cmd, system_element_context* context, const char* text, int x, int y, system_color base_color)
{
    if (!context || !text) return;

    system_color text_color = base_color;
    text_color.red   = clamp_text_channel(base_color.red);
    text_color.green = clamp_text_channel(base_color.green);
    text_color.blue  = clamp_text_channel(base_color.blue);

    int current_x = x;
    int current_y = y;

    for (int i = 0; text[i] != '\0'; i++) 
    {
        unsigned char character_token = (unsigned char)text[i];

        // Handle newline wrap layout parameters cleanly if specified
        if (character_token == '\n') {
            current_x = x;
            current_y += 16; // Standard 16px font line spacing height metric
            continue;
        }

        // Unsupported characters are skipped but still advance the cursor
        if (character_token < font_first_char || character_token > font_last_char) {
            current_x += font_glyph_width;
            continue;
        }

        const unsigned char* glyph = g_font_bitmap[character_token - font_first_char];

        for (int row = 0; row < font_glyph_height; row++) 
        {
            unsigned char row_bits = glyph[row];
            if (row_bits == 0) continue;

            // Merge each horizontal run of lit pixels into a single quad
            int col = 0;
            while (col < font_glyph_width) 
            {
                if (!((row_bits >> (7 - col)) & 1)) {
                    col++;
                    continue;
                }

                int run_start = col;
                while (col < font_glyph_width && ((row_bits >> (7 - col)) & 1)) {
                    col++;
                }

                push_quad_element(cmd, (float)(current_x + run_start), (float)(current_y + row), (float)(col - run_start), 1.0f, text_color);
            }
        }

        current_x += font_glyph_width; // Advance layout boundary tracker horizontally by standard char width
    }
}

int get_text_width(const char* text) {
    if (!text) return 0;
    return (int)strlen(text) * font_glyph_width; 
}